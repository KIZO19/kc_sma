CREATE TABLE IF NOT EXISTS discipline_auditions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    discipline_id INT NOT NULL,
    school_id INT NOT NULL,
    student_id INT NOT NULL,
    created_by INT NOT NULL,
    hearing_at DATETIME NOT NULL,
    location VARCHAR(255) NULL,
    alleged_facts TEXT NOT NULL,
    student_statement TEXT NOT NULL,
    observations TEXT NULL,
    decision TEXT NULL,
    parent_meeting_at DATETIME NOT NULL,
    parent_meeting_location VARCHAR(255) NULL,
    parent_notice TEXT NULL,
    email_status ENUM('pending', 'sent', 'failed', 'skipped') NOT NULL DEFAULT 'pending',
    email_details TEXT NULL,
    sms_status ENUM('pending', 'sent', 'failed', 'skipped') NOT NULL DEFAULT 'pending',
    sms_details TEXT NULL,
    report_status ENUM('pending', 'sent', 'partial', 'failed', 'no_recipients') NOT NULL DEFAULT 'pending',
    report_details TEXT NULL,
    recipient_user_ids TEXT NULL,
    report_sent_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_discipline_auditions_entry (discipline_id, hearing_at),
    KEY idx_discipline_auditions_school (school_id, created_at),
    CONSTRAINT fk_discipline_auditions_incident
        FOREIGN KEY (discipline_id) REFERENCES discipline_eleves (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
